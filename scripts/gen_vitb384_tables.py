"""Supplementary tables and figure for the ViT-B/16-384 comparison from results/vitb384_comparison/augreg_b384/report.json
(the densified, single-session report of 2026-10-25). Writes tables/vitb384_pairs.tex (every LEAF
schedule and every latency pair it forms, as tables/latency_pairs_detail.tex; since 2026-10-26 it also replaces the former
tables/vitb384_schedules.tex, which schedules_table still writes but the supplementary no longer inputs)
and figures/vitb384_frontier.pdf (val and V2 against batch-32 latency). Usage: python scripts/gen_vitb384_tables.py"""
import json
import re
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
REP = ROOT / 'results/vitb384_comparison/augreg_b384/report.json'
PLANS = ROOT / 'results/vitb384_comparison/augreg_b384/plans.json'
OUT_T = ROOT / 'paper/kbs_paper/tables'
OUT_F = ROOT / 'paper/kbs_paper/figures'
FAM = {'ToMe+M3': 'ToMe+MLERP'}
XLIM, YVAL, YV2 = (35, 120), (76, 87), (64, 78)
HEAD = '% Generated by scripts/gen_vitb384_tables.py from results/vitb384_comparison/augreg_b384/report.json; do not edit by hand.'


def schedules_table(rep, plans):
    pts = {p['name']: p for p in rep['points']}; dense = pts['ref/dense']
    rows = []
    for name, p in sorted(((n, p) for n, p in pts.items() if p['family'] == 'LEAF'), key=lambda x: x[1]['ms']):
        job = plans['jobs'][name]; cfg = job['config']
        k = sum(1 for l in range(len(cfg.get('merge_keep', []))) if cfg['merge_keep'][l] < (cfg['merge_keep'][l - 1] if l else 577)) if 'merge_keep' in cfg else None
        rows.append((job['budget']['id'].replace('dense', ''), job['budget']['value'], p['ms'], dense['ms'] / p['ms'], p['gmac'], p['val'], p['val'] - dense['val'], p['v2'], p['v2'] - dense['v2'], k))
    lines = [HEAD, r'\begin{table}[t]\centering\small\setlength{\tabcolsep}{4pt}',
             f"\\caption{{\\ours\\ on \\mbox{{ViT-B/16}} at 384 pixels (577 tokens), batch~32 on the RTX~5060~Ti: dense {dense['ms']:.1f}\\,ms, val {dense['val']:.2f}, V2 {dense['v2']:.2f}. Budgets $L$ are fractions of the dense latency measured before planning; ms: measured latency of the planned schedule in the comparison session; $\\Delta$: minus dense (points); $K$: number of stations.}}",
             r'\label{tab:s-vitb384-schedules}',
             r'\begin{tabular}{l r r r r rr rr r}\toprule',
             r'Budget & $L$ (ms) & ms & speed-up & GMAC & Val & $\Delta$ & V2 & $\Delta$ & $K$ \\ \midrule']
    for b, L, ms, sp, g, val, dv, v2, d2, k in rows:
        lines.append(f"{b}$\\times$ & {L:.1f} & {ms:.1f} & {sp:.2f}$\\times$ & {g:.1f} & {val:.2f} & {dv:+.2f} & {v2:.2f} & {d2:+.2f} & {k if k is not None else '--'} \\\\")
    lines += [r'\bottomrule\end{tabular}\end{table}']
    (OUT_T / 'vitb384_schedules.tex').write_text('\n'.join(lines) + '\n')
    return rows


def param(ref):
    tail = ref.split('/')[-1]
    m = re.match(r'([a-z_]+)(.*)', tail)
    if not m: return tail
    k, v = m.groups()
    return {'r': 'r', 'kr': 'keep', 'keep_rate': 'keep', 'ratio': 'ratio', 'n': 'n', 'k': 'k'}.get(k, k) + '=' + v


def pairs_table(rep, plans):
    pts = {p['name']: p for p in rep['points']}; dense = pts['ref/dense']
    tests = rep['latency_pairs']
    cell = lambda x: f"{x['delta']:+.2f}" + ('$^{*}$' if x['holm'] < .05 else '')
    sched = {name: r for name, r in zip(sorted((n for n, p in pts.items() if p['family'] == 'LEAF'), key=lambda n: pts[n]['ms']), schedules_table(rep, plans))}
    head = r'$L$ & $K$ & GMAC & ms & Val & V2 & Family & Point & ms & Val & V2 & $\Delta$Val & $\Delta$V2 \\'
    lines = [HEAD, r'\begin{table}[t]\centering\scriptsize\setlength{\tabcolsep}{2pt}',
             f"\\caption{{Every \\ours\\ schedule on \\mbox{{ViT-B/16}} at 384 pixels and every latency pair it forms ({len(tests)} pairs), laid out as \\cref{{tab:s-pairs-detail}}; $L$ is $0.40$--$0.80\\times$ the dense latency measured before planning. Baseline grids were densified near the \\ours\\ latencies; $^{{*}}$: significant after Holm correction over the {len(tests)} pairs of a split. DiffRate publishes no schedule for this backbone. A point $r{{=}}a\\,\\mathrm{{i}}\\,b$ is a densified point with a per-layer count that decreases or increases linearly across blocks (mean $a$, inflection $b$ as in ToMe); the other densified points have fractional ratios.}}",
             r'\label{tab:s-vitb384-pairs}',
             r'\begin{tabular}{rrrrrr l l rrrrr}\toprule',
             r'\multicolumn{6}{c}{\ours} & \multicolumn{7}{c}{Paired point} \\ \cmidrule(lr){1-6}\cmidrule(lr){7-13}',
             head + r' \midrule',
             f"\\multicolumn{{13}}{{l}}{{dense: {dense['ms']:.2f}\\,ms, Val {dense['val']:.2f}, V2 {dense['v2']:.2f}}} \\\\"]
    budgets = sorted({t['ours'] for t in tests}, key=lambda o: pts[o]['ms'])
    tot = dict(pairs=0, vw=0, vl=0, w2=0, l2=0); dv, d2 = [], []
    for o in budgets:
        a = pts[o]; _, L, _, _, g, _, _, _, _, k = sched[o]
        lead = f"{L:.1f} & {k if k is not None else '--'} & {g:.1f} & {a['ms']:.2f} & {a['val']:.2f} & {a['v2']:.2f}"
        for t in sorted([t for t in tests if t['ours'] == o], key=lambda t: FAM.get(t['family'], t['family'])):
            r = pts[t['ref']]
            lines.append(f"{lead} & {FAM.get(t['family'], t['family'])} & {param(t['ref'])} & {r['ms']:.2f} & {r['val']:.2f} & {r['v2']:.2f} & {cell(t['val'])} & {cell(t['v2'])} \\\\")
            lead = ' & & & & &'; tot['pairs'] += 1
            tot['vw'] += t['val']['holm'] < .05 and t['val']['delta'] > 0; tot['vl'] += t['val']['holm'] < .05 and t['val']['delta'] < 0
            tot['w2'] += t['v2']['holm'] < .05 and t['v2']['delta'] > 0; tot['l2'] += t['v2']['holm'] < .05 and t['v2']['delta'] < 0
            dv.append(t['val']['delta']); d2.append(t['v2']['delta'])
    lines += [r'\bottomrule\end{tabular}\end{table}']
    (OUT_T / 'vitb384_pairs.tex').write_text('\n'.join(lines) + '\n')
    return tot, dv, d2, min(t['val']['ci_lo'] for t in tests), min(t['v2']['ci_lo'] for t in tests)


def figure(rep):
    import matplotlib; matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    import sys; sys.path.insert(0, str(ROOT))
    import leaf.reproduction.experiments.campaign_reports as q
    fig, axes = plt.subplots(1, 2, figsize=(7.0, 3.0)); omitted = set()
    for ax, s, lab, yl in zip(axes, ('val', 'v2'), ('ImageNet val top-1 (%)', 'ImageNet-V2 top-1 (%)'), (YVAL, YV2)):
        for fam in sorted({p['family'] for p in rep['points']}):
            allp = [p for p in rep['points'] if p['family'] == fam and p['ms'] <= XLIM[1]]
            omitted |= {p['name'] for p in allp if p[s] < yl[0]}
            pts = sorted((p['ms'], p[s]) for p in allp)
            if not pts: continue
            color = q.COLORS.get(fam, 'black' if fam == 'dense' else q.GRAY)
            if fam != 'dense':
                front = [pts[i] for i in sorted(q.pareto(pts))]
                ax.plot(*zip(*front), color=color, lw=1.4 if fam == 'LEAF' else .7, zorder=3 if fam == 'LEAF' else 2)
            ax.scatter(*zip(*pts), s=22 if fam in ('LEAF', 'dense') else 12, color=color, marker='*' if fam == 'dense' else q.MARKERS.get(fam.split(' ')[0], 'o'),
                       label=FAM.get(fam, fam), zorder=4 if fam == 'LEAF' else 2)
        ax.set_xlabel('latency, batch 32 (ms)'); ax.set_ylabel(lab); ax.set_xlim(*XLIM); ax.set_ylim(*yl); ax.grid(alpha=.3, lw=.4)
    axes[1].legend(fontsize=6, ncol=2, loc='lower right')
    fig.tight_layout(); fig.savefig(OUT_F / 'vitb384_frontier.pdf'); plt.close(fig)
    return len(omitted)


def main():
    rep = json.loads(REP.read_text()); plans = json.loads(PLANS.read_text())
    rows = schedules_table(rep, plans); tot, dv, d2, lo_v, lo_2 = pairs_table(rep, plans); n_omit = figure(rep)
    print('pairs', tot, 'mean dval', round(float(np.mean(dv)), 2), 'median', round(float(np.median(dv)), 2), 'min', round(min(dv), 2),
          '| mean dv2', round(float(np.mean(d2)), 2), 'median', round(float(np.median(d2)), 2), 'min', round(min(d2), 2),
          '| lowest CI bound val', round(lo_v, 2), 'v2', round(lo_2, 2), '| points below the plotted range', n_omit)
    print('schedules', [(b, round(ms, 1), round(sp, 2), round(dv, 2), round(d2, 2), k) for b, L, ms, sp, g, val, dv, v2, d2, k in rows])


if __name__ == '__main__':
    main()
