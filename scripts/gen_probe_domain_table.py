"""Supplementary table on out-of-domain probe images from results/probe_domain/report.json (DeiT-B re-planned from
1,000 unlabelled MS-COCO images). Usage: python scripts/gen_probe_domain_table.py > paper/kbs_paper/tables/probe_domain.tex"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'results/probe_domain'


def main():
    r = json.loads((ROOT / 'report.json').read_text()); rows = sorted(r['rows'], key=lambda x: x['budget_ms']); s = r['summary']['deit_b']['coco1000'] if 'deit_b' in r['summary'] else next(iter(r['summary'].values()))
    cell = lambda x: f"{x['delta']:+.2f}" + ('$^{*}$' if x['holm'] < .05 else '')
    out = ['% Generated by scripts/gen_probe_domain_table.py from results/probe_domain/report.json (2026-10-25); do not edit by hand.',
           r'\begin{table}[t]\centering\small\setlength{\tabcolsep}{4pt}',
           r'\caption{Out-of-domain probe images. The seven latency budgets of \mbox{DeiT-B} re-planned from the 1,917 probe configurations measured on 1,000 unlabelled MS-COCO images (the first 1,000 even-indexed images of the Karpathy test split) instead of the 5,000 ImageNet calibration images, with the released head groups, \cost\ model and budgets; released: the released schedule, re-timed in the same session. $K$: stations; $\hat F$: surrogate value of the planned schedule on its own probe images; $\Delta$: COCO-planned minus released (points); $^{*}$: significant (McNemar, Holm over the seven budgets of a split).}',
           r'\label{tab:s-probe-domain}',
           r'\begin{tabular}{l rr rr rr rr}\toprule',
           r' & \multicolumn{2}{c}{$K$} & \multicolumn{2}{c}{ms} & \multicolumn{2}{c}{Val} & \multicolumn{2}{c}{V2} \\ \cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}',
           r'Budget (ms) & released & COCO & released & COCO & released & $\Delta$ & released & $\Delta$ \\ \midrule']
    for x in rows:
        out.append(f"{x['budget_ms']:.1f} & {x['K_ref']} & {x['K']} & {x['ms_ref']:.2f} & {x['ms']:.2f} & {x['val']['top1_ref']:.2f} & {cell(x['val'])} & {x['v2']['top1_ref']:.2f} & {cell(x['v2'])} \\\\")
    out += [r'\midrule', f"mean & & & & & & {s['mean_delta_val']:+.2f} & & {s['mean_delta_v2']:+.2f} \\\\", r'\bottomrule\end{tabular}\end{table}']
    print('\n'.join(out))
    import sys; print('summary', {k: s[k] for k in ('changed', 'n', 'win_val', 'loss_val', 'win_v2', 'loss_v2', 'mean_dlat_pct', 'met_budget')}, file=sys.stderr)


if __name__ == '__main__':
    main()
