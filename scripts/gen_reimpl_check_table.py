"""Supplementary table: our re-implementations of RAPID and ToFu (and the official ToMe) against the numbers printed in the
RAPID paper (Choi and Jang, 2026, Table 1: ImageNet-1K top-1 of ToMe, ToFu and RAPID at r = 11, 14, 17, 20 on DeiT-B
and ViT-B/16), at the grid points our campaign shares with that table (r = 14 and r = 20). Our numbers are the
same-session re-run accuracies of the main campaign (results/main_comparison_analysis/report_leaf.json).
Usage: python scripts/gen_reimpl_check_table.py > paper/kbs_paper/tables/reimpl_check.tex"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# RAPID paper, Table 1 (top-1 %, ImageNet-1K), as printed.
PUBLISHED = {
    'deit_b': dict(dense=81.97, dense_ours=81.83, ToMe={14: 79.42, 20: 66.47}, ToFu={14: 80.23, 20: 71.03}, RAPID={14: 80.52, 20: 72.03}),
    'augreg_b': dict(dense=85.11, dense_ours=85.23, ToMe={14: 83.41, 20: 73.25}, ToFu={14: 83.72, 20: 75.26}, RAPID={14: 84.17, 20: 77.54}),
}
NAMES = {'deit_b': 'DeiT-B', 'augreg_b': 'ViT-B (AugReg)'}


def main():
    d = json.loads((ROOT / 'results/main_comparison_analysis/report_leaf.json').read_text())
    out = ['% Generated by scripts/gen_reimpl_check_table.py from results/main_comparison_analysis/report_leaf.json and Table 1 of the RAPID paper; do not edit by hand.',
           r'\begin{table}[t]\centering\small\setlength{\tabcolsep}{5pt}',
           r'\caption{Re-implementation check. ImageNet val top-1 of our same-session re-runs of ToMe (official code), ToFu and RAPID (re-implemented) at the two grid points shared with Table~1 of the RAPID paper~\cite{choi2026rapid}, beside the numbers printed there (their evaluation pipeline differs slightly: the dense models differ by $-0.14$ and $+0.12$~points). $\Delta$: ours minus published.}',
           r'\label{tab:s-reimpl}',
           r'\fitbox{\begin{tabular}{l l r rr rr}\toprule',
           r' & & & \multicolumn{2}{c}{$r=14$} & \multicolumn{2}{c}{$r=20$} \\ \cmidrule(lr){4-5}\cmidrule(lr){6-7}',
           r'Backbone & Method & dense & published / ours & $\Delta$ & published / ours & $\Delta$ \\ \midrule']
    for bb, pub in PUBLISHED.items():
        arms = {(a['family'], a['name'].split('/')[-1]): a['val'] for a in d['arms'][bb] if a['family'] in ('ToMe', 'ToFu', 'RAPID')}
        dense = pub['dense_ours']          # our same-session dense evaluation (Supp. published-numbers table)
        for i, fam in enumerate(('ToMe', 'ToFu', 'RAPID')):
            cells = []
            for r in (14, 20):
                ours = arms.get((fam, f'r{r}')); p = pub[fam][r]
                cells.append(f"{p:.2f} / {ours:.2f} & {ours - p:+.2f}" if ours is not None else '-- & --')
            lead = f"{NAMES[bb]} & " if i == 0 else ' & '
            dcell = (f"{pub['dense']:.2f} / {dense:.2f}" if dense is not None else f"{pub['dense']:.2f}") if i == 0 else ''
            out.append(f"{lead}{fam} & {dcell} & " + ' & '.join(cells) + r' \\')
        out.append(r'\midrule' if bb == 'deit_b' else '')
    out = [o for o in out if o != ''] + [r'\bottomrule\end{tabular}}\end{table}']
    print('\n'.join(out))


if __name__ == '__main__':
    main()
