"""Supplementary long table: every latency-paired comparison of the main campaign with its numbers (the pairs behind
main Table 1): per backbone and LEAF budget, the LEAF schedule (measured ms, val, V2) and, for each family paired within
tau, the paired point (its parameter, ms, val, V2) and the paired differences with Holm significance.
Source: results/main_comparison_analysis/report_leaf.json (tests + arms). Usage:
  python scripts/gen_latency_pairs_detail.py > paper/kbs_paper/tables/latency_pairs_detail.tex"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAMES = {'deit_t': 'DeiT-T', 'deit_s': 'DeiT-S', 'deit_b': 'DeiT-B', 'augreg_s': 'ViT-S (AugReg)', 'augreg_b': 'ViT-B (AugReg)',
         'mae_b': 'ViT-B (MAE)', 'mae_l': 'ViT-L (MAE)'}
ORDER = list(NAMES)
FAM = {'ToMe+M3': 'ToMe+MLERP'}
EXCLUDE = {'LEAF-M0'}


def param(ref):
    """Short label of a baseline point from its arm name, e.g. ref/baseline/tome/r13 -> r=13; DR10.0 -> 10.0 GMAC."""
    tail = ref.split('/')[-1]
    if tail.startswith('DR'): return f'{tail[2:]}\\,GMAC'
    m = re.match(r'([a-z_]+)(.*)', tail)
    if not m: return tail
    k, v = m.groups()
    return {'r': 'r', 'kr': 'keep', 'keep_rate': 'keep', 'ratio': 'ratio', 'n': 'n', 'k': 'k'}.get(k, k) + '=' + v


def main():
    d = json.loads((ROOT / 'results/main_comparison_analysis/report_leaf.json').read_text())
    arms = {bb: {a['name']: a for a in rows} for bb, rows in d['arms'].items()}
    tests = [t for t in d['tests'] if t['family'] not in EXCLUDE]
    cell = lambda x: f"{x['delta']:+.2f}" + ('$^{*}$' if x['holm'] < .05 else '')
    out = [r'% Generated by scripts/gen_latency_pairs_detail.py from results/main_comparison_analysis/report_leaf.json; do not edit by hand.',
           r'{\scriptsize\setlength{\tabcolsep}{1.5pt}',
           r'\begin{longtable}{l l l l r r r r r}',
           r'\caption{Every latency-paired comparison of the main campaign (the pairs summarised in \maintab{v2-pairs}): for each backbone and \ours\ budget, the \ours\ schedule (measured batch-32 latency, ImageNet val and V2 top-1) and, for every family with a point within $\tau=\max(0.05\,\mathrm{ms},2\,\mathrm{SD})$, that point (its parameter, latency, val, V2) and the paired differences $\Delta$ (\ours\ minus the point, in points); $^{*}$: significant after Holm correction over all pairs of a split. Families without a point within $\tau$ of a budget are absent from that budget.}\label{tab:s-pairs-detail}\\',
           r'\toprule', r'Budget & \ours\ ms / Val / V2 & Family & Point & ms & Val & V2 & $\Delta$Val & $\Delta$V2 \\ \midrule\endfirsthead',
           r'\multicolumn{9}{c}{\tablename\ \thetable\ (continued)}\\ \toprule', r'Budget & \ours\ ms / Val / V2 & Family & Point & ms & Val & V2 & $\Delta$Val & $\Delta$V2 \\ \midrule\endhead',
           r'\bottomrule\endlastfoot']
    n = 0
    for bb in ORDER:
        rows = [t for t in tests if t['backbone'] == bb]
        if not rows: continue
        dense = next((a for a in arms[bb].values() if a['family'] == 'dense'), None)
        out.append(f"\\multicolumn{{9}}{{l}}{{\\emph{{{NAMES[bb]}}}" + (f"\\quad dense: {dense['ms']:.2f}\\,ms, Val {dense['val']:.2f}, V2 {dense['v2']:.2f}" if dense else '') + "} \\\\*")
        budgets = sorted({t['ours'] for t in rows}, key=lambda o: arms[bb][o]['ms'])
        for o in budgets:
            a = arms[bb][o]; pairs = sorted([t for t in rows if t['ours'] == o], key=lambda t: t['family'])
            first = True
            for t in pairs:
                r = arms[bb][t['ref']]
                lead = (f"{o.split('/')[-1]} & {a['ms']:.2f} / {a['val']:.2f} / {a['v2']:.2f}" if first else " &")
                out.append(f"{lead} & {FAM.get(t['family'], t['family'])} & {param(t['ref'])} & {r['ms']:.2f} & {r['val']:.2f} & {r['v2']:.2f} & {cell(t['val'])} & {cell(t['v2'])} \\\\")
                first = False; n += 1
    out += [r'\end{longtable}}']
    print('\n'.join(out))
    import sys; print(f'% {n} pairs', file=sys.stderr)


if __name__ == '__main__':
    main()
