"""Supplementary long table: every LEAF schedule of the main campaign and every latency pair it forms (the pairs behind
main Table 1, plus the pairs with early LEAF that share its Holm family): per backbone and LEAF budget, the LEAF schedule
(budget L, stations K, GMAC, measured ms, val, V2) and, for each family paired within tau, the paired point (its parameter,
ms, val, V2) and the paired differences with Holm significance. Budgets without a pair are listed with '--'.
Replaces the former results_all_budgets.tex and leaf_vs_m0.tex tables (2026-10-26).
Source: results/main_comparison_analysis/report_leaf.json (tests + arms); dense numbers from tables/results_all_budgets.tex.
Usage:
  python scripts/gen_latency_pairs_detail.py > paper/kbs_paper/tables/latency_pairs_detail.tex"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAMES = {'deit_t': 'DeiT-T', 'deit_s': 'DeiT-S', 'deit_b': 'DeiT-B', 'augreg_s': 'ViT-S (AugReg)', 'augreg_b': 'ViT-B (AugReg)',
         'mae_b': 'ViT-B (MAE)', 'mae_l': 'ViT-L (MAE)'}
ORDER = list(NAMES)
FAM = {'ToMe+M3': 'ToMe+MLERP', 'LEAF-M0': r'early \ours'}


def param(ref):
    """Short label of a baseline point from its arm name, e.g. ref/baseline/tome/r13 -> r=13; DR10.0 -> 10.0 GMAC."""
    tail = ref.split('/')[-1]
    if tail.startswith('DR'): return f'{tail[2:]}\\,GMAC'
    m = re.match(r'([a-z_]+)(.*)', tail)
    if not m: return tail
    k, v = m.groups()
    return {'r': 'r', 'kr': 'keep', 'keep_rate': 'keep', 'ratio': 'ratio', 'n': 'n', 'k': 'k'}.get(k, k) + '=' + v


def dense_rows():
    """Dense ms/val/V2 per backbone, from the audited header lines of tables/results_all_budgets.tex."""
    txt = (ROOT / 'paper/kbs_paper/tables/results_all_budgets.tex').read_text()
    hits = re.findall(r'\\emph\{\\mbox\{([^}]*)\}([^}]*)\}\\quad dense: ([0-9.]+)\\,ms, Val ([0-9.]+), V2 ([0-9.]+)', txt)
    by_name = {(a + b).strip(): (float(ms), float(v), float(v2)) for a, b, ms, v, v2 in hits}
    return {bb: by_name[n] for bb, n in NAMES.items() if n in by_name}


def main():
    d = json.loads((ROOT / 'results/main_comparison_analysis/report_leaf.json').read_text())
    arms = {bb: {a['name']: a for a in rows} for bb, rows in d['arms'].items()}
    dense = dense_rows()
    cell = lambda x: f"{x['delta']:+.2f}" + ('$^{*}$' if x['holm'] < .05 else '')
    fam = lambda t: FAM.get(t['family'], t['family'])
    head = r'$L$ & $K$ & GMAC & ms & Val & V2 & Family & Point & ms & Val & V2 & $\Delta$Val & $\Delta$V2 \\'
    out = [r'% Generated by scripts/gen_latency_pairs_detail.py from results/main_comparison_analysis/report_leaf.json; do not edit by hand.',
           r'{\scriptsize\setlength{\tabcolsep}{1.8pt}',
           r'\begin{longtable}{rrrrrr l l rrrrr}',
           r'\caption{Every \ours\ schedule of the main campaign and every latency pair it forms (the pairs of \maintab{v2-pairs}, and the pairs with early \ours\ of \cref{sec:s-repro} that share their Holm correction). Left: the \ours\ schedule, with its latency budget $L$ (ms), stations $K$, GMAC, measured batch-32 latency (ms) and ImageNet val and V2 top-1. Right: for every family with a point within $\tau=\max(0.05\,\mathrm{ms},2\,\mathrm{SD})$, that point (its parameter, latency, val, V2) and the paired differences $\Delta$ (\ours\ minus the point, in points); $^{*}$: significant after Holm correction over all pairs of a split. --: no point of any family within $\tau$.}\label{tab:s-pairs-detail}\\',
           r'\toprule', r'\multicolumn{6}{c}{\ours} & \multicolumn{7}{c}{Paired point} \\ \cmidrule(lr){1-6}\cmidrule(lr){7-13}',
           head + r' \midrule\endfirsthead',
           r'\multicolumn{13}{c}{\tablename\ \thetable\ (continued)}\\ \toprule', head + r' \midrule\endhead',
           r'\bottomrule\endlastfoot']
    n = 0
    for bb in ORDER:
        if bb not in arms: continue
        tests = [t for t in d['tests'] if t['backbone'] == bb]
        ms, v, v2 = dense[bb]
        out.append(f"\\multicolumn{{13}}{{l}}{{\\emph{{{NAMES[bb]}}}\\quad dense: {ms:.2f}\\,ms, Val {v:.2f}, V2 {v2:.2f}}} \\\\*")
        leaf = sorted((a for a in arms[bb].values() if a['family'] == 'LEAF'), key=lambda a: a['ms'])
        for a in leaf:
            lead = f"{a['budget']:.2f} & {a['K']} & {a['gmac']:.2f} & {a['ms']:.2f} & {a['val']:.2f} & {a['v2']:.2f}"
            pairs = sorted([t for t in tests if t['ours'] == a['name']], key=lambda t: (t['family'] == 'LEAF-M0', fam(t)))
            if not pairs:
                out.append(lead + r' & -- & & & & & & \\'); continue
            for t in pairs:
                r = arms[bb][t['ref']]
                pt = f"{r['gmac']:.2f}\\,GMAC" if t['family'] == 'LEAF-M0' else param(t['ref'])
                out.append(f"{lead} & {fam(t)} & {pt} & {r['ms']:.2f} & {r['val']:.2f} & {r['v2']:.2f} & {cell(t['val'])} & {cell(t['v2'])} \\\\")
                lead = ' & & & & &'; n += 1
    out += [r'\end{longtable}}']
    print('\n'.join(out))
    import sys; print(f'% {n} pairs, {sum(1 for bb in arms for a in arms[bb].values() if a["family"] == "LEAF")} schedules', file=sys.stderr)


if __name__ == '__main__':
    main()
