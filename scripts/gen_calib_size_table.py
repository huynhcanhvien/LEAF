"""Supplementary table on the calibration-set size from results/calib_size/report.json.
Usage: python scripts/gen_calib_size_table.py > paper/kbs_paper/tables/calib_size.tex"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'results/calib_size'
LABEL = {'n1000_s0': ('1,000', 'draw 1'), 'n1000_s1': ('1,000', 'draw 2'), 'n1000_s2': ('1,000', 'draw 3'),
         'n2500_s0': ('2,500', 'draw 1'), 'n2500_s1': ('2,500', 'draw 2'), 'n5000': ('5,000', 'released set'),
         'n5000_odd': ('5,000', 'disjoint set'), 'n10000': ('10,000', 'both sets')}


def main():
    r = json.loads((ROOT / 'report.json').read_text()); s = r['summary']; rows = r['rows']
    out = ['% Generated by scripts/gen_calib_size_table.py from results/calib_size/report.json (2026-10-24); do not edit by hand.',
           r'\begin{table}[t]\centering\small\setlength{\tabcolsep}{4pt}',
           r'\caption{Calibration-set size. Every latency budget of \mbox{DeiT-S}, \mbox{DeiT-B} and \mbox{ViT-B} (MAE) (20 budgets) is re-planned from the same probe configurations, \cost\ model and planner, with the probe KL averaged over a subset of the 5,000 released calibration images (draws without replacement), over the disjoint other half of the class-balanced 10,000-image set (probed for this table), or over both halves. chg.: schedules that differ from the released one; $\Delta$: re-planned minus released, mean over the 20 budgets (ImageNet val and V2 points; latency in percent, batch 32, one timing session); wins/losses: significant after Holm correction over the 20 pairs of a split; met: budgets whose measured latency is within the budget (released schedules: 18 of 20).}',
           r'\label{tab:s-calib-size}',
           r'\fitbox{\begin{tabular}{l l r rr rr r r}\toprule',
           r'Images & Set & chg. & $\Delta$val & $\Delta$V2 & wins/losses val & wins/losses V2 & $\Delta$latency (\%) & met \\ \midrule']
    for k, (n, lab) in LABEL.items():
        v = s[k]
        out.append(f"{n} & {lab} & {v['changed']}/{v['n']} & {v['mean_delta_val']:+.2f} & {v['mean_delta_v2']:+.2f} & "
                   f"{v['win_val']}/{v['loss_val']} & {v['win_v2']}/{v['loss_v2']} & {v['mean_dlat_pct']:+.2f} & {v['met_budget']}/{v['n']} \\\\")
    out += [r'\bottomrule\end{tabular}}\end{table}']
    print('\n'.join(out))


if __name__ == '__main__':
    main()
