"""Supplementary table S-salt-low from results/salt_low_coverage/report.json (prediction error of the frozen and the extended
SALT model). With --replan, the re-planned schedules (replan_report.json, replan_accuracy.json) are added; the paper does
not use them (decision 2026-10-24: constant margin confounds the comparison).
Usage: python scripts/gen_salt_low_coverage_table.py [--replan] > paper/kbs_paper/tables/salt_low_coverage.tex"""
import sys
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'results/salt_low_coverage'
NAMES = {'deit_t': 'DeiT-T', 'deit_s': 'DeiT-S', 'deit_b': 'DeiT-B', 'augreg_s': 'ViT-S (AugReg)', 'augreg_b': 'ViT-B (AugReg)',
         'mae_b': 'ViT-B (MAE)', 'mae_l': 'ViT-L (MAE)'}
BUDGETS = ('low90', 'low80', 'low70')


def load(p): return json.loads(Path(p).read_text())


def main(replan='--replan' in sys.argv):
    rep = {(t['backbone'], t['name'].split('/')[-1]): t for t in load(ROOT / 'report.json')['rows']}
    rp = {(t['backbone'], t['name']): t for t in load(ROOT / 'replan_report.json')['rows']}
    acc = {(t['backbone'], t['budget']): t for t in load(ROOT / 'replan_accuracy.json')['rows']}
    errs_f = [t['err_frozen_pct'] for t in rep.values()]; errs_e = [t['err_ext_pct'] for t in rep.values()]
    met_ext = sum(rp[(bb, 'ext/' + b)]['met'] for bb in NAMES for b in BUDGETS)
    met_orig = sum(rp[(bb, 'full/latency/' + b)]['met'] for bb in NAMES for b in BUDGETS)
    n = len(rep)
    cell = lambda d: f"{d['delta']:+.2f}" + ('$^{*}$' if d['holm'] < .05 else '')
    out = [
        '% Generated by scripts/gen_salt_low_coverage_table.py from results/salt_low_coverage/{report,replan_report,replan_accuracy}.json (2026-10-24); do not edit by hand.',
        r'\begin{table}[t]\centering\footnotesize\setlength{\tabcolsep}{3pt}',
        r'\caption{\cost\ below the range of its timing data. For the 21 low-budget schedules of the main paper (budgets at 0.9, 0.8 and 0.7 of the fastest timed schedule), the latency predicted by the frozen \cost\ model (fitted on 27--48 workloads at batch~32) and by the extended model (the same workloads plus 8--9 GMAC-planned workloads at 0.20--0.30$\times$ the dense GMAC, timed in one session) against the latency measured in the low-budget campaign; error in percent of the measured latency.' + (r' Right: the budgets re-planned with the extended model, timed in one session with the original schedules (met: measured latency within the budget) and evaluated on ImageNet val and V2; $\Delta$: re-planned minus original, in points; $^{*}$: significant after Holm correction over the 21 pairs of a split.' if replan else '') + '}',
        r'\label{tab:s-salt-low}',
        (r'\fitbox{\begin{tabular}{l l r r rr | rr c rr}\toprule' if replan else r'\fitbox{\begin{tabular}{l l r r rr}\toprule'),
        (r' & & & & \multicolumn{2}{c|}{Prediction error (\%)} & \multicolumn{5}{c}{Re-planned with the extended model} \\' if replan
         else r' & & & & \multicolumn{2}{c}{Prediction error (\%)} \\'),
        (r'Backbone & Budget & Budget (ms) & Measured (ms) & frozen & extended & Predicted (ms) & Measured (ms) & met & $\Delta$ val & $\Delta$ V2 \\ \midrule' if replan
         else r'Backbone & Budget & Budget (ms) & Measured (ms) & frozen & extended \\ \midrule')]
    for bb, label in NAMES.items():
        for i, b in enumerate(BUDGETS):
            t, e, a = rep[(bb, b)], rp[(bb, 'ext/' + b)], acc[(bb, b)]
            row = f"{label if i == 0 else ''} & {b} & {t['budget_ms']:.2f} & {t['measured_ms']:.2f} & {t['err_frozen_pct']:+.1f} & {t['err_ext_pct']:+.1f}"
            if replan: row += f" & {e['predicted_ms']:.2f} & {e['ms']:.2f} & {'yes' if e['met'] else 'no'} & {cell(a['val'])} & {cell(a['v2'])}"
            out.append(row + ' \\\\')
    mape = lambda v: sum(abs(x) for x in v) / len(v)
    dv = [a['val']['delta'] for a in acc.values()]; d2 = [a['v2']['delta'] for a in acc.values()]
    out += [r'\midrule',
            f"\\multicolumn{{4}}{{l}}{{Mean signed error / MAPE / max}} & {sum(errs_f) / n:+.1f} / {mape(errs_f):.1f} / {max(abs(x) for x in errs_f):.1f} & "
            f"{sum(errs_e) / n:+.1f} / {mape(errs_e):.1f} / {max(abs(x) for x in errs_e):.1f}"
            + (f" & \\multicolumn{{3}}{{c}}{{{met_ext} of 21 met (original schedules re-timed: {met_orig} of 21)}} & {sum(dv) / n:+.2f} & {sum(d2) / n:+.2f}" if replan else '') + ' \\\\',
            r'\bottomrule\end{tabular}}\end{table}']
    print('\n'.join(out))


if __name__ == '__main__':
    main()
