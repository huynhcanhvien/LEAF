"""Depth summary of the released latency-planned schedules (CPU only):  paper/tables/schedule_summary.tex

    python -m leaf.reproduction.report.schedule_summary

Input: assets/schedules/<backbone>.json (the 'leaf/latency/*' entries). Stations are binned by depth into thirds of the
network; the final-block station is counted separately. Per third: number of stations, mean theta, mean alpha and the
share of all removed tokens (final station included in the total). 'First half': range over the budgets of the share of
removed tokens that are removed in blocks < B/2.
"""
import json
from pathlib import Path
import sys

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO))
import numpy as np

from leaf.backbones import SPECS
from leaf.reproduction.report.tables import NAMES, BBS

OUT = REPO / 'paper/tables/schedule_summary.tex'


def summary(bb):
    spec = SPECS[bb]; depth, n0 = spec.depth, spec.n_tokens
    book = json.loads((REPO / 'assets/schedules' / f'{bb}.json').read_text())['schedules']
    entries = [e for name, e in book.items() if name.startswith('leaf/latency/')]
    thirds = {t: [] for t in range(3)}; removed = np.zeros(4); ks, final, first_half = [], 0, []
    for e in entries:
        st = e['stations']; ks.append(len(st)); n, half, total = n0, 0, 0
        for s in st:
            drop = n - s['tokens_after']; n = s['tokens_after']; total += drop
            if s['block'] < depth // 2: half += drop
            if s['block'] == depth - 1: final += 1; removed[3] += drop; continue
            t = min(2, s['block'] * 3 // depth); thirds[t].append((s['theta'], s['alpha'])); removed[t] += drop
        first_half.append(half / total if total else 0.)
    share = removed / removed.sum()
    cells = []
    for t in range(3):
        a = np.array(thirds[t])
        cells += [str(len(a)), f'{a[:, 0].mean():.2f}' if len(a) else '--', f'{a[:, 1].mean():.2f}' if len(a) else '--',
                  f'{100 * share[t]:.0f}']
    return (f"\\mbox{{{NAMES[bb]}}} & {len(entries)} & {min(ks)}--{max(ks)} & " + ' & '.join(cells) +
            f" & {final} & {100 * min(first_half):.0f}--{100 * max(first_half):.0f} \\\\")


def main():
    rows = [summary(bb) for bb in BBS]
    head = ('\\begin{table*}[t]\\centering\\small\n'
            '\\caption{Structure of the 48 latency-planned schedules of \\ours\\ (\\cref{tab:v2-main}) by depth. Stations are binned '
            'into thirds of the blocks; the final-block station is counted separately. Per third: number of stations over all '
            'budgets ($n$), mean merge share $\\bar\\theta$ ($0$: prune only, $1$: merge only), mean forecast weight $\\bar\\alpha$, '
            'and the share of all removed tokens removed there (\\%). Last column: range over the budgets of the share of removed '
            'tokens that are removed in the first half of the network. Generated by \\texttt{leaf/reproduction/report/'
            'schedule\\_summary.py} from \\texttt{assets/schedules}.}\\label{tab:schedule-summary}\n'
            '\\setlength{\\tabcolsep}{3pt}\n'
            '\\begin{tabular}{l r r rrrr rrrr rrrr r r}\\toprule\n'
            ' & & & \\multicolumn{4}{c}{First third} & \\multicolumn{4}{c}{Middle third} & \\multicolumn{4}{c}{Last third} & & \\\\ '
            '\\cmidrule(lr){4-7}\\cmidrule(lr){8-11}\\cmidrule(lr){12-15}\n'
            'Backbone & Budgets & $K$ & $n$ & $\\bar\\theta$ & $\\bar\\alpha$ & \\% & $n$ & $\\bar\\theta$ & $\\bar\\alpha$ & \\% & '
            '$n$ & $\\bar\\theta$ & $\\bar\\alpha$ & \\% & Final & First half (\\%) \\\\ \\midrule\n')
    OUT.write_text(head + '\n'.join(rows) + '\n\\bottomrule\\end{tabular}\\end{table*}\n'); print('wrote', OUT)


if __name__ == '__main__':
    main()
